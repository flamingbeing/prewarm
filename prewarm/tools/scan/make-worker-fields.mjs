// node prewarm/tools/scan/make-worker-fields.mjs <form-map.json>: writes worker/fields.js, the Worker's list of fields it
// may read (worker/read.js), from make-form-map.py's output. Only ids, types, labels, units and options go in (the same
// as js/schema.js), never the form itself. A cell that may be sent keeps its type (num, int, code, time); everything else
// gets a type the Worker refuses: 'tick' (read on the phone), 'header' (Subject ID, Date of Entry), or its own (text...).
import { readFileSync, writeFileSync } from 'node:fs';

const fm = JSON.parse(readFileSync(process.argv[2], 'utf8')), out = {};
for (const f of fm.fields) {
  const type = f.kind === 'tick' ? 'tick' : f.send ? f.type : ['num', 'int', 'code', 'time'].includes(f.type) ? 'header' : f.type;
  if (out[f.id] && out[f.id].type !== type) throw new Error(`${f.id}: two places with different types`);
  out[f.id] = { type, label: f.label || f.id, unit: f.unit || '', opts: f.opts || null };
}
const lines = Object.entries(out).sort(([a], [b]) => a < b ? -1 : 1).map(([id, f]) => `  ${JSON.stringify(id)}: ${JSON.stringify(f)},`);
writeFileSync(new URL('../../../worker/fields.js', import.meta.url), `// The fields the Worker will read (worker/read.js): id -> { type, label, unit, opts }. Only num, int, code and time cells
// are ever sent to the reading model; any other id or type (IDs, dates, names, free text, the page header, ticks) is
// refused. GENERATED by prewarm/tools/scan/make-worker-fields.mjs from the form map (form version 3.2): do not hand-edit.
export const FIELDS = {
${lines.join('\n')}
};
`);
console.log(`${lines.length} fields (${Object.values(out).filter(f => ['num', 'int', 'code', 'time'].includes(f.type)).length} readable) in worker/fields.js`);
